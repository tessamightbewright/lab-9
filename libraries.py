import numpy as np
import matplotlib.pyplot as plt
days = np.array([1, 2, 3, 4, 5, 6, 7])
revenue = np.array([500, 600, 989, 700, 100, 600, 520])
costs = np.array([400, 250, 500, 700, 50, 200, 310])
print("days: ", days)
print("revenue: ", revenue)
print("costs: ", costs)
profit = revenue - costs
print("profit: ", profit)
np.mean(profit)
print("mean profit: ", np.mean(profit))
np.min(profit)
print("minimum profit: ", np.min(profit))
np.max(profit)
print("maximum profit: ", np.max(profit))
plt.plot(days, profit)
plt.xlabel("Days")
plt.ylabel("Profit")
plt.title("Profit over Time")
plt.show()